// module-top-level statement here hits gl_model.ts's `const MAX_VERTS`
// before that module has reached its own declaration, a TDZ
// ReferenceError. Deferring the read into a function body (this file's
// side of PORTING.md's import-cycle rule -- gl_mesh.ts is the least
// fundamental module in this cycle) avoids it: every caller below reaches
// this well after the whole module graph has finished loading.
interface SLerpedState {
  buffer: Float32Array;
  rows: Float32Array[];
}
let sLerpedState: SLerpedState | null = null;
function getSLerped(): SLerpedState {
  if (sLerpedState) return sLerpedState;
  const buffer = new Float32Array(MAX_VERTS * 4);
  const rows = Array.from({ length: MAX_VERTS }, (_unused, i) => buffer.subarray(i * 4, i * 4 + 4));
  sLerpedState = { buffer, rows };
  return sLerpedState;
}

