function GL_LerpVerts(
  nverts: number,
  v: readonly AliasVertexT[],
  ov: readonly AliasVertexT[],
  verts: readonly AliasVertexT[],
  lerp: readonly Float32Array[],
  move: Vec3,
  frontv: Vec3,
  backv: Vec3,
): void {
  // PMM -- added RF_SHELL_DOUBLE, RF_SHELL_HALF_DAM
  if (currententity && isShellFlags(currententity.flags)) {
    for (let i = 0; i < nverts; i++) {
      const normal = r_avertexnormals[verts[i].lightnormalindex];
      const out = lerp[i];
      out[0] = move[0] + ov[i].v[0] * backv[0] + v[i].v[0] * frontv[0] + normal[0] * POWERSUIT_SCALE;
      out[1] = move[1] + ov[i].v[1] * backv[1] + v[i].v[1] * frontv[1] + normal[1] * POWERSUIT_SCALE;
      out[2] = move[2] + ov[i].v[2] * backv[2] + v[i].v[2] * frontv[2] + normal[2] * POWERSUIT_SCALE;
    }
  } else {
    for (let i = 0; i < nverts; i++) {
      const out = lerp[i];
      out[0] = move[0] + ov[i].v[0] * backv[0] + v[i].v[0] * frontv[0];
      out[1] = move[1] + ov[i].v[1] * backv[1] + v[i].v[1] * frontv[1];
      out[2] = move[2] + ov[i].v[2] * backv[2] + v[i].v[2] * frontv[2];
    }
  }
}

